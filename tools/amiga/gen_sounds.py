"""The Amiga client's sounds: the game's own (data/sounds/default), as 8-bit signed samples at 8 kHz
for Paula, into src/platform/amiga/sounds_8bit.h (amiga_sound.c copies them to chip memory).
Regeneration needs sndfile-convert to decode the original skull laugh.

    tools/amiga/gen_sounds.py
"""
import os
import subprocess
import tempfile
import wave

RATE = 8000
SOUNDS = ["cannon", "hit", "explode_small", "explode", "splat", "pickup", "engine", "skull_laugh"]
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..")

def read_samples(path):
    with wave.open(path) as wav:
        if wav.getsampwidth() != 2 or wav.getnchannels() != 1:
            raise SystemExit(path + ": mono 16-bit WAVs only")
        rate = wav.getframerate()
        frames = wav.readframes(wav.getnframes())
    return rate, [int.from_bytes(frames[i:i + 2], "little", signed=True) for i in range(0, len(frames), 2)]


def resample(rate, src):
    n = int(len(src) * RATE / rate) & ~1                 # (Paula plays words: an even length)
    data = []
    for i in range(n):                                   # (each 8 kHz sample: the average of what it covers)
        a, b = int(i * rate / RATE), max(int((i + 1) * rate / RATE), int(i * rate / RATE) + 1)
        data.append(sum(src[a:b]) // (b - a))
    return data


def skull_laugh():
    source = os.path.join(root, "data", "sounds", "original", "laugh-evil-1.ogg")
    with tempfile.TemporaryDirectory() as temporary:
        wav = os.path.join(temporary, "laugh.wav")
        subprocess.run(["sndfile-convert", "-pcm16", source, wav], check=True)
        rate, src = read_samples(wav)
    # Keep the clearest part of the laugh, with short fades to avoid clicks.
    data = resample(rate, src[rate * 72 // 100:rate * 228 // 100])
    gain = 112 * 256 / max(map(abs, data))
    for i, value in enumerate(data):
        fade = min(1, i / (RATE * 0.018), (len(data) - 1 - i) / (RATE * 0.100))
        data[i] = round(value * gain * fade)
    return data


out = []
lens = []
for name in SOUNDS:
    src = skull_laugh() if name == "skull_laugh" else resample(*read_samples(
        os.path.join(root, "data", "sounds", "default", name + ".wav")))
    data = [max(-128, min(127, value >> 8)) for value in src]
    lens.append(len(data))
    rows = [", ".join(str(v) for v in data[i:i + 24]) for i in range(0, len(data), 24)]
    out.append("static const signed char snd_%s[%d] = {\n    %s\n};" % (name, len(data), ",\n    ".join(rows)))
with open(os.path.join(root, "src", "platform", "amiga", "sounds_8bit.h"), "w") as f:
    f.write("/* SPDX-License-Identifier: MIT */\n/* Generated by tools/amiga/gen_sounds.py: signed 8-bit at %d Hz.\n" % RATE)
    f.write(" * The skull laugh is from AntumDeluge's Evil Laugh (CC0), see CREDITS.md. */\n")
    f.write("#define SND_RATE %d\n" % RATE)
    f.write("enum { %s, SND_COUNT };\n" % ", ".join("SND_" + s.upper() for s in SOUNDS))
    f.write("\n".join(out) + "\n")
    f.write("static const signed char *const snd_data[SND_COUNT] = { %s };\n" % ", ".join("snd_" + s for s in SOUNDS))
    f.write("static const unsigned short snd_len[SND_COUNT] = { %s };\n" % ", ".join(str(n) for n in lens))
print("sounds_8bit.h: %d sounds, %d bytes" % (len(SOUNDS), sum(lens)))

