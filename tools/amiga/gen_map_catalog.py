#!/usr/bin/env python3
"""Build the Amiga's menu index from the desktop's bundled map headers."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
maps = root / "data/maps"
worlds = {"classic", "desert", "jungle", "winter", "scifi", "volcanic", "wasteland", "moon", "swamp"}
# Local mode order: flag, conquest, hardpoint, TDM, kill confirmed, annihilation, warlord.
mode_bits = {"flag": 1, "conquest": 6, "hardpoint": 6, "deathmatch": 24,
             "killconfirmed": 24, "annihilation": 32, "warlord": 64}
entries = []
for path in sorted(maps.rglob("*.ofpmap")):
    header = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line == "tiles":
            break
        if "=" in line:
            key, value = line.split("=", 1)
            header[key] = value
    if header.get("size") == "huge" or path.parent.name in {"original", "classic"}:
        continue
    biome = header.get("biome", "classic")
    if biome == "scifi":
        continue
    if biome not in worlds:
        raise ValueError(f"{path}: unknown world {biome}")
    size = header.get("size", "large")
    if size not in {"small", "medium", "large"}:
        raise ValueError(f"{path}: unknown size {size}")
    arena = header.get("arena") == "yes"
    modes = 0
    for mode in header.get("modes", "").replace(",", " ").split():
        modes |= mode_bits[mode]
    if "modes" not in header:
        modes = 32 if arena else 95
    entries.append((header.get("name", path.stem), path.relative_to(maps).as_posix(), biome, size, arena, modes))

lines = ["/* SPDX-License-Identifier: MIT */",
         "/* Generated by tools/amiga/gen_map_catalog.py from data/maps. */",
         "#ifndef OFP_AMIGA_MAP_CATALOG_TYPE", "#define OFP_AMIGA_MAP_CATALOG_TYPE",
         "struct CatalogMap { const char *name, *file; Biome biome; int size, arena; unsigned modes; };", "#endif",
         "static const struct CatalogMap catalog_maps[] = {"]
for name, path, world, size, arena, modes in sorted(entries, key=lambda entry: entry[0].casefold()):
    lines.append(f"    {{ {json.dumps(name)}, {json.dumps(path)}, BIOME_{world.upper()}, SIZE_{size.upper()}, {int(arena)}, {modes} }},")
lines.append("};")
(root / "src/platform/amiga/map_catalog.h").write_text("\n".join(lines) + "\n")
sys.path.insert(0, str(root / "tools" / "amiga"))
from amiga_headers import ids_only   # noqa: E402
ids_only(str(root / "src/platform/amiga/map_catalog.h"))
