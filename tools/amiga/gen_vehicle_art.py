"""Native 16-colour world vehicles inspired by the credited OGA references."""
from pathlib import Path
from native_art import tank, direction_atlas
from gen_classic_art import add_sprite_bank
from amiga_palette import Nearest, RGB
root = Path(__file__).resolve().parents[2]
pens=(Nearest(RGB,(0,3,4,5,8,10,11,12)),Nearest(RGB,(0,4,5,9,10,12,13,14)))
lines=['/* SPDX-License-Identifier: MIT */','/* Generated by tools/amiga/gen_vehicle_art.py */']
for world in ('classic','volcanic','moon'):
    atlas=direction_atlas([(tank(team,world=world,cls=cls),32) for cls in range(3) for team in range(2)]).tobytes()
    add_sprite_bank(lines,world+'_vehicles',atlas,range(6),32,pens)
(root/'src/platform/amiga/vehicle_art.h').write_text('\n'.join(lines)+'\n')
