"""Connected ice, oil and dry crater tiles; shared artwork, native planar Amiga data."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
PENS = ((10, 5, 7, 12, 5, 10), (12, 0, 4, 5, 7, 12), (0, 0, 12, 5, 4, 0))

def tile(kind, mask):
    out = []
    for y in range(16):
        row = []
        for x in range(16):
            h = (x * 193 + y * 977 + x * y * 31) & 255
            edge = min(16 if mask & 1 else y, 16 if mask & 2 else 15-x,
                       16 if mask & 4 else 15-y, 16 if mask & 8 else x)
            if kind == 0:
                c = 0
                if edge < 1: c = 1
                elif edge < 2: c = 2
                if (4 <= y <= 8 and x == 4 + (y-4)//3) or (9 <= y <= 11 and x == y-3): c = 2
                if y == 8 and 5 <= x <= 8: c = 1
                if y == 3 and 9 <= x <= 12: c = 1
            elif kind == 1:
                c = 0 if edge < 1 or (edge < 3 and h < 80) else 1
                if edge > 3 and ((y == 6 and 4 <= x <= 8) or (y == 7 and 8 <= x <= 10)): c = 4
            else:
                c = 0 if edge > 3 else (3 if y < 4 or x < 4 else 1)
                if edge == 2: c = 2
                if edge > 4 and h < 9: c = 1
            row.append(c)
        out.append(row)
    return out

def braces(a):
    if isinstance(a, int): return str(a)
    return '{' + ','.join(braces(x) for x in a) + '}'

pixels = [[tile(k, m) for m in range(16)] for k in range(3)]
head = '/* SPDX-License-Identifier: MIT */\n/* Generated by tools/gen_surface_art.py. */\n'
(ROOT/'src/platform/sdl2/surface_art.h').write_text(head + 'static const unsigned char surface_pixels[3][16][16][16] = ' + braces(pixels) + ';\n')
planes = []
for k in range(3):
    cells = []
    for m in range(16):
        for q in range(4):
            cells.append([[sum(((PENS[k][pixels[k][m][(q//2)*8+y][(q%2)*8+x]] >> p) & 1) << (7-x) for x in range(8))
                           for y in range(8)] for p in range(4)])
    planes.append(cells)
(ROOT/'src/platform/amiga/surface_art.h').write_text(head + 'static const unsigned char surface_tiles[3][64][4][8] = ' + braces(planes) + ';\n')
