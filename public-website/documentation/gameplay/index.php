<h2 id="first-match">Your first match</h2>
<p>Sign into a player profile and choose Training for a guided introduction, or Local Game to choose a world, map and game mode. Other local players join with their own controls. In the team screen, choose your side and tank, then mark yourself ready.</p>
<p>Desktop clients support up to four local players; AmigaOS supports two. Network matches support up to eight tanks, including bots, within the selected map's capacity.</p>
<h2 id="combat">Combat and rescue</h2>
<p>Keep an eye on armour, fuel and your remaining tanks. Walls and buildings can be destroyed to open a route. Mines arm after a short delay, so leave yourself room to move away.</p>
<p>Free prisoners, drive close to pick them up and take them to a friendly first-aid building. Rescued soldiers leave your tank and enter the building. Large treetops provide cover: tanks drive beneath them and only the covered parts are hidden.</p>
<h2 id="modes">Game modes</h2>
<dl class="documentation-modes">
  <dt>Classic</dt><dd>Fight through the enemy base, rescue soldiers and bring the enemy flag home under the original-style rules.</dd>
  <dt>Capture the Flag</dt><dd>Steal the opposing flag and return it to your base while protecting your own.</dd>
  <dt>Conquest</dt><dd>Capture checkpoints and hold them to score. The capture bar shows your progress and the top of the screen shows the team totals.</dd>
  <dt>Hardpoint</dt><dd>Fight for the active checkpoint, then move when the objective changes.</dd>
  <dt>Team Deathmatch</dt><dd>Destroy enemy tanks to reach the team's kill target.</dd>
  <dt>Kill Confirmed</dt><dd>Collect enemy tags to confirm kills; recover friendly tags to deny a point.</dd>
  <dt>Annihilation</dt><dd>Every tank fights for itself. The last survivor wins.</dd>
  <dt>Warlord</dt><dd>Protect your team's boss tank and destroy the opposing Warlord.</dd>
</dl>
<h2 id="classic">Classic and enhanced worlds</h2>
<p>Classic keeps the original style of play and its three tank classes. Enhanced worlds introduce additional vehicles, weather, slippery terrain and optional power-ups. Those additions are disabled under Classic rules. A map determines which game modes and environmental settings it supports.</p>
<h2 id="radar">Reading the radar</h2>
<p>The radar follows your tank and shows a nearby part of the battlefield. Game Options chooses its detail. Tanks use their team colours; flags appear within range in Classic and Capture the Flag, and nearby checkpoints appear in Conquest-style modes.</p>
<h2 id="replays">Training, replays and awards</h2>
<p>Training teaches movement, weapons, rescue and flag capture. Tools contains the benchmark and Replays &amp; Awards. Select a saved replay to watch a previous battle, or view the awards earned by your profiles.</p>
<p>For control setup and online play, continue to <a href="/documentation/clients/">Clients &amp; controls</a>.</p>
