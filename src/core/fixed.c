fx fx_sin(angle16 a) { return sin_table[a >> 8]; }
fx fx_cos(angle16 a) { return sin_table[(uint16_t)(a + 0x4000) >> 8]; }

/* Fractional division for 0 <= numerator <= denominator <= 2^31. */
static uint32_t ratio_q16(uint32_t numerator, uint32_t denominator)
{
    uint32_t result = 0;
    int bit;
    if (numerator == denominator)
        return 65536u;
    for (bit = 0; bit < 16; bit++) {
        numerator <<= 1;
        result <<= 1;
        if (numerator >= denominator) {
            numerator -= denominator;
            result |= 1u;
        }
    }
    return result;
}

angle16 fx_atan2(fx dx, fx dy)
{
    /* angle from north, clockwise: atan2(east, north). One octant from
     * atan(t) ~ t*pi/4 + 0.273*t*(1-t) (error < 0.25 deg), then mirror. */
    int64_t e = dx, n = -(int64_t)dy;
    int64_t ae = e < 0 ? -e : e, an = n < 0 ? -n : n;
    int64_t t, oct;
    uint32_t q;
    if (ae == 0 && an == 0)
        return 0;
    if (ae <= an) {
        t = ratio_q16((uint32_t)ae, (uint32_t)an);                       /* 0..65536 */
        oct = (8192 * t + ((2848 * t * (65536 - t)) >> 16)) >> 16;
        q = (uint32_t)oct;                         /* 0..8192 from the n axis */
    } else {
        t = ratio_q16((uint32_t)an, (uint32_t)ae);
        oct = (8192 * t + ((2848 * t * (65536 - t)) >> 16)) >> 16;
        q = 16384u - (uint32_t)oct;
    }
    if (e >= 0 && n >= 0) return (angle16)q;
    if (e >= 0)           return (angle16)(32768u - q);
    if (n < 0)            return (angle16)(32768u + q);
    return (angle16)(65536u - q);
}
